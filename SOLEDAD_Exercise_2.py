num = 11
while (num > 0):
  num = num - 1
  print(num)
print("Time is up!")

# The code will basically check if num is greater than 0. If 11 is greater than 0, then loop body runs.
# It will then calculate num - 1 as 11 - 1 = 10 and changes num from 11 to 10. This will then continue until the number reaches 0.
# Once the number reaches 0, the code will print "Time is up!".
