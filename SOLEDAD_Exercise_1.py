for num in range(2, 21, 2):
  print(num)

# So basically it starts with line 1, where in range(2, 21, 2) means the code will start with 2, 21 is the code's stop value. 
# (But since 21 is exclusive, it will stop at 20)
# And the second 2 means the count will be stepping by 2.
# For instance, the number 2 is the starting output, then it will go to line 2, which will be printed as the first line in the output. 
# This will go on until the output reaches the number 20.
